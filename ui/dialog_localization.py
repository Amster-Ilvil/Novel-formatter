def _translate_dialog_atom(source: str, language: str) -> str:
    """Translate one complete UI fragment while preserving unknown/user data."""
    if not source:
        return source
    base = translate_text(source, language)
    if base != source:
        return base
    exact = (_JA if language == LANG_JA else _EN).get(source)
    if exact is not None:
        return exact
    for pattern, replacer in _DIALOG_LINE_PATTERNS.get(language, ()):
        match = pattern.fullmatch(source)
        if match:
            return replacer(match)
    return source


def translate_dialog_text(text: str | None, language: str) -> str:
    """Translate dialog chrome only, never free-form document/error payloads.

    Dynamic dialogs are translated through a small whitelist of anchored line
    templates.  Captured paths, model names, counts and other payload values
    are inserted verbatim, so localization cannot mutate business identifiers.
    """
    source = "" if text is None else str(text)
    language = normalize_language(language)
    if language == LANG_ZH or not source:
        return source

    whole = _translate_dialog_atom(source, language)
    if whole != source or "\n" not in source:
        return whole

    # Long status dialogs are assembled from stable UI lines plus dynamic
    # values. Translate each complete line independently and preserve newlines
    # byte-for-byte. Unknown lines (tracebacks, paths, OCR/model output) remain
    # untouched.
    parts = source.splitlines(keepends=True)
    out: list[str] = []
    for part in parts:
        body = part.rstrip("\r\n")
        ending = part[len(body):]
        out.append(_translate_dialog_atom(body, language) + ending)
    return "".join(out)

