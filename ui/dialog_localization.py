def _translate_risk_details(value: str, language: str) -> str:
    text = str(value)
    if language == LANG_EN:
        text = re.sub(r"(\d+) 组高风险修改", r"\1 high-risk change group(s)", text)
        text = re.sub(r"(\d+) 组与参考草稿明显相反的修改", r"\1 change group(s) clearly opposed by the reference draft", text)
        return text.replace("、", ", ")
    text = re.sub(r"(\d+) 组高风险修改", r"高リスク変更 \1 グループ", text)
    text = re.sub(r"(\d+) 组与参考草稿明显相反的修改", r"参照草稿と明確に反する変更 \1 グループ", text)
    return text.replace("、", "、")


